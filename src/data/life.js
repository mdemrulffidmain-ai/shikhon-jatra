// প্রশ্ন তৈরি: স্থির প্রশ্ন বা যন্ত্র দিয়ে তৈরি প্রশ্ন
export function lessonQuestions(i) {
  return LESSONS[i].qs.map((q) => {
    const r = typeof q === 'string' ? GEN[q]() : q;
    const idx = shuffle(r.o.map((_, k) => k));
    return { p: r.p, o: idx.map((k) => r.o[k]), a: idx.indexOf(r.a), why: r.why };
  });
}
