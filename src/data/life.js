// প্রতিটি পাঠে কয়েকটি কার্ড পড়তে হয়, তারপর প্রশ্ন। ভুল হলে কারণ দেখানো হয়।
import { bd, shuffle, rnd } from '../lib/util.js';

// এলোমেলো সংখ্যার প্রশ্ন তৈরির যন্ত্র
const num3 = (ans) => {
  const set = new Set([ans]);
  [ans + 1, ans - 1, ans + 2, ans - 2, ans + 3].forEach((v) => { if (v >= 0 && set.size < 3) set.add(v); });
  return shuffle([...set]);
};
const numQ = (p, ans, why) => {
  const vals = num3(ans);
  return { p, o: vals.map((v) => bd(v) + ' টাকা'), a: vals.indexOf(ans), why };
};

export const GEN = {
  profit() {
    const buy = 3 + rnd(8), gain = 1 + rnd(5), sell = buy + gain;
    return numQ(`${bd(buy)} টাকায় কিনে ${bd(sell)} টাকায় বেচলে লাভ কত?`, gain,
      `লাভ = বিক্রির দাম − কেনার দাম। ${bd(sell)} − ${bd(buy)} = ${bd(gain)}।`);
  },
  change() {
    const pay = [10, 20, 50][rnd(3)], price = 3 + rnd(pay === 10 ? 6 : 14), back = pay - price;
    return numQ(`${bd(pay)} টাকা দিয়ে ${bd(price)} টাকার জিনিস কিনলে ফেরত কত?`, back,
      `ফেরত = যা দিয়েছি − জিনিসের দাম। ${bd(pay)} − ${bd(price)} = ${bd(back)}।`);
  },
  save() {
    const a = [2, 3, 5][rnd(3)], w = 2 + rnd(3), tot = a * w;
    return numQ(`প্রতি সপ্তাহে ${bd(a)} টাকা জমালে ${bd(w)} সপ্তাহে কত জমবে?`, tot,
      `${bd(a)} টাকা করে ${bd(w)} বার। ${bd(a)} × ${bd(w)} = ${bd(tot)}।`);
  },
  total() {
    const a = 2 + rnd(5), b = 2 + rnd(5), t = a + b;
    return numQ(`একটি খাতার দাম ${bd(a)} টাকা আর একটি কলমের দাম ${bd(b)} টাকা। দুটো মিলে কত?`, t,
      `মোট = ${bd(a)} + ${bd(b)} = ${bd(t)}।`);
  }
};

